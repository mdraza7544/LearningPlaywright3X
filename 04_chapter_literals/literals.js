//todo JavaScript Literals

//! What is a Literal?
// A literal is a fixed value written directly in the code.

// Example:
let name = "Rahul";
// "Rahul" is a string literal



// Types of Literals

//! 1. String Literal
// Text written inside quotes.

let studentName = "Rahul";
let course = 'MCA';


//! 2. Number Literal
// Numbers written directly.

let age = 22;
let price = 500.50;


//! 3. Boolean Literal
// Represents true or false.

let isStudent = true;
let isPassed = false;


//! 4. Null Literal
// Represents an empty or unknown value.

let result = null;


//! 5. Undefined
// A variable without a value has undefined.

let address;


//! 6. Array Literal
// Collection of values written inside [ ].

let marks = [80, 75, 90];


//! 7. Object Literal
// Data written as key-value pairs inside { }.

let student = {
    name: "Rahul",
    age: 22,
    course: "MCA"
};


//! Quick Revision
// String  -> "Rahul"
// Number  -> 22
// Boolean -> true / false
// Null    -> null
// Undefined -> undefined
// Array   -> [10, 20, 30]
// Object  -> { name: "Rahul", age: 22 }