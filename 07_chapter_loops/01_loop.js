// JavaScript Loop
// What is a Loop?
// A loop is used to repeat the same block of code
// multiple times.


/*
Example:

If we want to print "Hello" 5 times,
without a loop we have to write:

console.log("Hello");
console.log("Hello");
console.log("Hello");
console.log("Hello");
console.log("Hello");

Using a loop, we can do it easily.
*/


// Basic Example
for (let i = 1; i <= 5; i++) {
    console.log("Hello");
}

