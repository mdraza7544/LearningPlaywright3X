// JavaScript if Statement
// The if statement is used to execute a block of code
// only when the condition is true.

let age = 20;
if (age >= 18) {
    console.log("You are eligible to vote.");
}

// Example 1: Check Age
let studentAge = 16;
if (studentAge >= 18) {
    console.log("Adult");
}

// Example 2: Check Marks
let marks = 75;

if (marks >= 40) {
    console.log("Pass");
}

// Example 3: Check Even Number
let number = 10;
if (number % 2 === 0) {
    console.log("Even Number");
}

// Example 4: Check Temperature
let temp = 35;
if (temp > 30) {
    console.log("Weather is Hot");
}

