//! JavaScript Assignment Operators\
// Assignment operators are used to assign values to variables.


//! 1. Assignment (=)
// Assigns a value to a variable.
let a = 10;
console.log(a);


//! 2. Addition Assignment (+=)
// Adds a value and assigns the result.
a += 5;   // a = a + 5
console.log(a);   // 15


//! 3. Subtraction Assignment (-=)
// Subtracts a value and assigns the result.
a -= 3;   // a = a - 3
console.log(a);   // 12


//! 4. Multiplication Assignment (*=)
// Multiplies a value and assigns the result.
a *= 2;   // a = a * 2
console.log(a);   // 24


//! 5. Division Assignment (/=)
// Divides a value and assigns the result.
a /= 4;   // a = a / 4
console.log(a);   // 6


//! 6. Remainder Assignment (%=)
// Finds the remainder and assigns the result.
a %= 4;   // a = a % 4
console.log(a);   // 2

//! 7. Exponentiation Assignment (**=)
// Raises a number to a power.
a **= 3;   // a = a ** 3
console.log(a);   // 8


//! Quick Revision
// =    -> Assign
// +=   -> Add and assign
// -=   -> Subtract and assign
// *=   -> Multiply and assign
// /=   -> Divide and assign
// %=   -> Remainder and assign
// **=  -> Power and assign