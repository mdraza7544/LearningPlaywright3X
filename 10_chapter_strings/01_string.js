//! STRING IN JAVASCRIPT
//? A string is a data type used to store text or a sequence of characters.

// We can create a string using:
// 1. Double quotes: " "
// 2. Single quotes: ' '
// 3. Backticks: ` `

// Example 1:
let name = "Ashif";
console.log(name);
// Output:Ashif

// Example 2:
let message = 'Hello World';
console.log(message);
// Output:Hello World

// Example 3:
let city = `Bangalore`;
console.log(city);
// Output:Bangalore

//! Simple Definition:
//? A string is a sequence of characters used to represent text in JavaScript.