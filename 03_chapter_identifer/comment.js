//! What is a Comment?
// A comment is text written in code to explain something.
// JavaScript ignores comments while executing the program.


//! 1. Single-line Comment
// We use // for a single-line comment.

// This is a single-line comment
let name = "Rahul";

let age = 22; // Student age


//! 2. Multi-line Comment
// We use /* */ for multiple lines.

/*
This is a multi-line comment.
It can contain multiple lines.
*/


// Comments can also be used to
// temporarily disable code.

// let marks = 90;
// console.log(marks);


//! Quick Revision
// Single-line  -> // comment
// Multi-line   -> /* comment */